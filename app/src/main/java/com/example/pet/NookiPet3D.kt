/** Bundled, original Nooki model generated by tools/pet-model/generate_nooki_glb.py. */
const val NOOKI_MODEL_ASSET = "models/nooki.glb"

/**
 * Clip names searched for each mood, first match wins (case-insensitive). The bundled model uses
 * the first name of each list; the aliases make most third-party / Mixamo-style rigs work as-is.
 */
private val MoodClipAliases: Map<PetMood, List<String>> = mapOf(
    PetMood.SLEEPING to listOf("Sleeping", "Sleep", "Rest", "Idle_Sleep", "Lie", "Idle"),
    PetMood.HAPPY to listOf("Happy", "Cheer", "Jump", "Dance", "Wave", "Idle_Happy", "Idle"),
    PetMood.ALERT to listOf("Alert", "LookAround", "Look", "Surprised", "HeadTurn", "Idle"),
    PetMood.OVERWHELMED to listOf("Overwhelmed", "Restless", "Panic", "Shake", "Nervous", "Run")
)

/**
 * Real-time 3D desk pet rendered with SceneView (Filament).
 *
 * - The glTF clip follows [mood] (Sleeping / Happy / Alert / Overwhelmed).
 * - Tap: squash-and-stretch hop with a spring, a haptic tick and a short Happy reaction.
 * - Tilt: the pet leans and turns with the phone (gravity sensor, only while resumed).
 * - [stageColor] tints the 3D backdrop so the stage shifts with urgency.
 *
 * Renders inside a SurfaceView, which Compose cannot clip, so rounded corners are drawn as a mask in
 * [surroundColor] (the color of whatever sits around the stage, usually the card container).
 *
 * @param fallback shown in Compose previews and if the model can't be loaded.
 */
@Composable
fun NookiPet3D(
    mood: PetMood,
    stageColor: Color,
    surroundColor: Color,
    modifier: Modifier = Modifier,
    modelAssetPath: String = NOOKI_MODEL_ASSET,
    cornerRadius: Dp = 28.dp,
    onPetTapped: () -> Unit = {},
    fallback: @Composable () -> Unit = {}
) {
    if (LocalInspectionMode.current) {
        Box(modifier) { fallback() }
        return
    }

    val context = LocalContext.current
    val haptics = LocalHapticFeedback.current
    val scope = rememberCoroutineScope()
    val currentOnPetTapped by rememberUpdatedState(onPetTapped)

    val engine = rememberEngine()
    val modelLoader = rememberModelLoader(engine)
    val environmentLoader = rememberEnvironmentLoader(engine)
    val environment = rememberEnvironment(environmentLoader, isOpaque = true)

    val modelNode = remember(modelLoader, modelAssetPath) {
        runCatching {
            ModelNode(
                modelInstance = modelLoader.createModelInstance(assetFileLocation = modelAssetPath),
                autoAnimate = false,
                scaleToUnits = 1.0f,
                centerOrigin = Position(0f, 0f, 0f)
            ).apply {
                isEditable = false
                isShadowCaster = true
            }
        }.getOrNull()
    }
    if (modelNode == null) {
        Box(modifier) { fallback() }
        return
    }

    // Keyed on the node so a new modelAssetPath swaps what the Scene renders; the old node is freed.
    val childNodes = remember(modelNode) { mutableStateListOf<Node>(modelNode) }
    DisposableEffect(modelNode) { onDispose { modelNode.destroy() } }
    val cameraNode = rememberCameraNode(engine) {
        position = Position(x = 0f, y = 0.02f, z = 1.75f)
    }

    // Rest transform produced by scaleToUnits/centerOrigin; procedural motion is layered on top.
    val baseScale = remember(modelNode) { modelNode.scale }
    val basePosition = remember(modelNode) { modelNode.position }

    // ---- Spring-driven micro-interactions ------------------------------------------------------
    val squash = remember { Animatable(1f) }      // 1 = rest, <1 squashed, >1 stretched
    val hop = remember { Animatable(0f) }         // world units on Y
    val spin = remember { Animatable(0f) }        // degrees on Y
    var reacting by remember { mutableStateOf(false) }

    fun react() {
        haptics.performHapticFeedback(HapticFeedbackType.LongPress)
        currentOnPetTapped()
        reacting = true
        scope.launch {
            squash.animateTo(0.8f, spring(stiffness = Spring.StiffnessHigh))
            launch { hop.animateTo(0.12f, spring(stiffness = Spring.StiffnessMedium)) }
            squash.animateTo(1.12f, spring(stiffness = Spring.StiffnessMedium))
            hop.animateTo(0f, spring(dampingRatio = Spring.DampingRatioMediumBouncy, stiffness = Spring.StiffnessMediumLow))
            squash.animateTo(1f, spring(dampingRatio = Spring.DampingRatioLowBouncy, stiffness = Spring.StiffnessMediumLow))
        }
        scope.launch {
            spin.animateTo(spin.targetValue + 360f, spring(dampingRatio = 0.72f, stiffness = Spring.StiffnessLow))
            spin.snapTo(spin.value % 360f)
        }
        scope.launch {
            delay(1_800L)
            reacting = false
        }
    }

    // ---- Mood -> glTF clip ---------------------------------------------------------------------
    val clipMood = if (reacting) PetMood.HAPPY else mood
    LaunchedEffect(modelNode, clipMood) {
        val index = modelNode.findClipFor(clipMood) ?: return@LaunchedEffect
        modelNode.playingAnimations.keys.toList().forEach { modelNode.stopAnimation(it) }
        modelNode.playAnimation(index, speed = 1f, loop = true)
    }
    // A soft settle "pop" whenever the mood itself changes masks the clip switch.
    LaunchedEffect(mood) {
        squash.snapTo(0.94f)
        squash.animateTo(1f, spring(dampingRatio = Spring.DampingRatioMediumBouncy, stiffness = Spring.StiffnessMediumLow))
    }

    // ---- Tilt --------------------------------------------------------------------------------
    val tilt = remember { TiltTracker() }
    LifecycleResumeEffect(tilt) {
        tilt.start(context)
        onPauseOrDispose { tilt.stop() }
    }

    // ---- Stage color (Filament skybox expects linear RGB) -------------------------------------
    SideEffect {
        environment.skybox?.setColor(
            stageColor.red.srgbToLinear(),
            stageColor.green.srgbToLinear(),
            stageColor.blue.srgbToLinear(),
            1f
        )
    }

    Box(modifier) {
        Scene(
            modifier = Modifier.fillMaxSize(),
            engine = engine,
            modelLoader = modelLoader,
            environmentLoader = environmentLoader,
            environment = environment,
            isOpaque = true,
            cameraNode = cameraNode,
            // Fixed, art-directed camera: no orbit/zoom, the pet reacts instead.
            cameraManipulator = null,
            childNodes = childNodes,
            onGestureListener = rememberOnGestureListener(
                onSingleTapConfirmed = { _, _ -> react() }
            ),
            onFrame = { frameTimeNanos ->
                tilt.smoothStep()
                val seconds = frameTimeNanos / 1_000_000_000.0
                // Subtle whole-body sway so even static custom models feel alive.
                val sway = (sin(seconds * 2.0 * PI / 6.0) * 3.0).toFloat()
                modelNode.rotation = Rotation(
                    x = tilt.pitch,
                    y = tilt.yaw + spin.value + sway,
                    z = tilt.roll
                )
                val s = squash.value
                val counter = 1f / sqrt(s)
                modelNode.scale = baseScale * Scale(counter, s, counter)
                modelNode.position = basePosition + Position(y = hop.value - (1f - s) * 0.25f)
            }
        )
        // Rounded "window" mask over the SurfaceView.
        Canvas(Modifier.fillMaxSize()) {
            val r = cornerRadius.toPx()
            val mask = Path().apply {
                fillType = PathFillType.EvenOdd
                addRect(androidx.compose.ui.geometry.Rect(0f, 0f, size.width, size.height))
                addRoundRect(RoundRect(0f, 0f, size.width, size.height, CornerRadius(r, r)))
            }
            drawPath(mask, surroundColor)
        }
    }
}

private fun ModelNode.findClipFor(mood: PetMood): Int? {
    val count = animationCount
    if (count == 0) return null
    val names = (0 until count).map { animator.getAnimationName(it).orEmpty().lowercase() }
    MoodClipAliases.getValue(mood).forEach { alias ->
        val i = names.indexOfFirst { it == alias.lowercase() }
        if (i >= 0) return i
    }
    MoodClipAliases.getValue(mood).forEach { alias ->
        val i = names.indexOfFirst { it.contains(alias.lowercase()) }
        if (i >= 0) return i
    }
    return mood.ordinal % count
}

private fun Float.srgbToLinear(): Float =
    if (this <= 0.04045f) this / 12.92f else ((this + 0.055f) / 1.055f).toDouble().pow(2.4).toFloat()

/**
 * Turns the gravity vector into gentle lean angles. A slow-moving baseline is subtracted so the pet
 * reacts to *changes* in how you hold the phone, not to the absolute holding angle.
 */
private class TiltTracker : SensorEventListener {
    private var sensorManager: SensorManager? = null
    private var gx = 0f
    private var gy = 0f
    private var gz = 0f
    private var baseX = 0f
    private var baseY = 0f
    private var baseZ = 0f
    private var hasBaseline = false

    var yaw = 0f
        private set
    var pitch = 0f
        private set
    var roll = 0f
        private set

    fun start(context: Context) {
        val sm = context.getSystemService(Context.SENSOR_SERVICE) as? SensorManager ?: return
        val sensor = sm.getDefaultSensor(Sensor.TYPE_GRAVITY) ?: sm.getDefaultSensor(Sensor.TYPE_ACCELEROMETER) ?: return
        sensorManager = sm
        sm.registerListener(this, sensor, SensorManager.SENSOR_DELAY_GAME)
    }

    fun stop() {
        sensorManager?.unregisterListener(this)
        sensorManager = null
        hasBaseline = false
    }

    override fun onSensorChanged(event: SensorEvent) {
        val alpha = 0.15f // low-pass (also strips linear acceleration if we fell back to accel)
        gx += (event.values[0] - gx) * alpha
        gy += (event.values[1] - gy) * alpha
        gz += (event.values[2] - gz) * alpha
        if (!hasBaseline) {
            baseX = gx; baseY = gy; baseZ = gz; hasBaseline = true
        }
        val drift = 0.01f // baseline catches up in a few seconds
        baseX += (gx - baseX) * drift
        baseY += (gy - baseY) * drift
        baseZ += (gz - baseZ) * drift
    }

    override fun onAccuracyChanged(sensor: Sensor?, accuracy: Int) = Unit

    /** Called once per rendered frame; eases the visible angles toward the sensor target. */
    fun smoothStep() {
        val g = SensorManager.GRAVITY_EARTH
        val dx = ((gx - baseX) / g).coerceIn(-1f, 1f)
        val dz = ((gz - baseZ) / g).coerceIn(-1f, 1f)
        val targetYaw = -dx * 35f
        val targetRoll = dx * 8f
        val targetPitch = -dz * 18f
        val k = 0.12f
        yaw += (targetYaw - yaw) * k
        roll += (targetRoll - roll) * k
        pitch += (targetPitch - pitch) * k
    }
}
