#!/usr/bin/env python3
"""
Generates Nooki's adaptive launcher icon (foreground, background, monochrome) as Android
VectorDrawables, plus an SVG preview. Standard library only:

    python3 tools/icon/generate_icon.py [preview_dir]

Design: Nooki's marigold face, tilted a few degrees for personality, winking, with the sky-blue
reminder bell under the chin "ringing". All artwork sits inside the 66dp adaptive-icon safe zone.
"""

import os
import sys

RES = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "app", "src", "main", "res")

FUR = "#EC8F2A"
FUR_DEEP = "#D9771F"
CREAM = "#FFE2BF"
INK = "#241B3A"
BLUSH = "#F27C8A"
INNER_EAR = "#F6A7A0"
NOSE = "#7A3B2E"
BELL = "#5CC8F2"
BELL_HI = "#C9F0FF"
BG_TOP = "#3D2C66"
BG_BOTTOM = "#171126"
GLOW = "#6B55B0"

TILT = -7.0  # degrees, pivot at the head centre
PIVOT = (54.0, 58.0)
FIT = 0.88  # uniform scale so ear tips stay inside the 66dp safe circle
FIT_PIVOT = (54.0, 54.0)


def ellipse(cx, cy, rx, ry):
    return (f"M{cx - rx:.2f},{cy:.2f} a{rx:.2f},{ry:.2f} 0 1,0 {2 * rx:.2f},0 "
            f"a{rx:.2f},{ry:.2f} 0 1,0 {-2 * rx:.2f},0 Z")


def mirror(d_points):
    return [(108 - x, y) for x, y in d_points]


def ear_path(p):
    (a, b, c, d, e, f, g, h, i, j) = p
    return (f"M{a[0]},{a[1]} C{b[0]},{b[1]} {c[0]},{c[1]} {d[0]},{d[1]} "
            f"C{e[0]},{e[1]} {f[0]},{f[1]} {g[0]},{g[1]} C{h[0]},{h[1]} {i[0]},{i[1]} {j[0]},{j[1]} Z")


EAR_L = [(35, 46), (30, 37), (28, 27), (31, 21.5), (33.5, 17.5), (38.5, 18.5), (42, 22), (46, 26), (49.5, 31.5), (51, 37)]
INNER_L = [(37.5, 41), (34.5, 35), (33.5, 28.5), (35, 25), (36.5, 22.5), (39.5, 23.5), (41.5, 26), (44, 29), (45.5, 32), (46, 35)]

HEAD = ellipse(54, 58, 23.5, 20.5)
MUZZLE = ellipse(54, 66.5, 10.5, 6.8)
NOSE_P = ellipse(54, 62.6, 2.7, 1.9)
EYE_L = ellipse(44.5, 56, 3.1, 3.9)
SHINE_L = ellipse(43.6, 54.6, 1.05, 1.2)
CHEEK_L = ellipse(39.5, 63.5, 3.7, 2.2)
CHEEK_R = ellipse(68.5, 63.5, 3.7, 2.2)
# Winking right eye: a closed crescent (fillable, so it can also be a hole in the monochrome layer).
WINK = "M58.6,57.2 Q63.5,51.6 68.4,57.2 Q63.5,54.3 58.6,57.2 Z"
WINK_STROKE = "M59.2,57 Q63.5,52.4 67.8,57"
MOUTH = "M50.6,68.2 Q54,71.2 57.4,68.2"

BELL_P = ellipse(54, 82.5, 4.6, 4.4)
BELL_SLOT = "M51.6,84.4 L56.4,84.4"
BELL_HI_P = ellipse(52.6, 81.2, 1.3, 1.0)
RING_1 = "M61.2,78.4 Q63.4,82.2 61.2,86.2"
RING_2 = "M65.0,76.6 Q68.2,82.2 65.0,88.0"


def fg_shapes():
    """(kind, d, color, extra) in painter's order; kind in fill|stroke."""
    tilted = [
        ("fill", ear_path(EAR_L), FUR_DEEP, {}),
        ("fill", ear_path(mirror(EAR_L)), FUR_DEEP, {}),
        ("fill", ear_path(INNER_L), INNER_EAR, {}),
        ("fill", ear_path(mirror(INNER_L)), INNER_EAR, {}),
        ("fill", HEAD, FUR, {}),
        ("fill", MUZZLE, CREAM, {}),
        ("fill", CHEEK_L, BLUSH, {"alpha": 0.8}),
        ("fill", CHEEK_R, BLUSH, {"alpha": 0.8}),
        ("fill", EYE_L, INK, {}),
        ("fill", SHINE_L, "#FFFFFF", {}),
        ("stroke", WINK_STROKE, INK, {"width": 2.3}),
        ("fill", NOSE_P, NOSE, {}),
        ("stroke", MOUTH, INK, {"width": 1.5}),
    ]
    upright = [
        ("fill", BELL_P, BELL, {}),
        ("fill", BELL_HI_P, BELL_HI, {}),
        ("stroke", BELL_SLOT, "#2A86B0", {"width": 1.1}),
        ("stroke", RING_1, BELL, {"width": 1.6, "alpha": 0.9}),
        ("stroke", RING_2, BELL, {"width": 1.6, "alpha": 0.55}),
    ]
    return tilted, upright


def vd_path(kind, d, color, extra):
    alpha = extra.get("alpha")
    if kind == "fill":
        a = f'\n        android:fillAlpha="{alpha}"' if alpha else ""
        return f'    <path\n        android:fillColor="{color}"{a}\n        android:pathData="{d}" />'
    a = f'\n        android:strokeAlpha="{alpha}"' if alpha else ""
    return (f'    <path\n        android:strokeColor="{color}"{a}\n        android:strokeWidth="{extra["width"]}"\n'
            f'        android:strokeLineCap="round"\n        android:strokeLineJoin="round"\n'
            f'        android:pathData="{d}" />')


def svg_path(kind, d, color, extra):
    alpha = extra.get("alpha", 1)
    if kind == "fill":
        return f'<path d="{d}" fill="{color}" fill-opacity="{alpha}"/>'
    return (f'<path d="{d}" fill="none" stroke="{color}" stroke-opacity="{alpha}" '
            f'stroke-width="{extra["width"]}" stroke-linecap="round" stroke-linejoin="round"/>')


HEADER = ('<?xml version="1.0" encoding="utf-8"?>\n'
          '<!-- Generated by tools/icon/generate_icon.py. Edit the script, not this file. -->\n')


def foreground_xml():
    tilted, upright = fg_shapes()
    indent = lambda s: "\n".join("    " + l for l in s.split("\n"))
    body = "\n".join(indent(vd_path(*s)) for s in tilted)
    rest = "\n".join(vd_path(*s) for s in upright)
    return (HEADER + '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="108dp"\n    android:height="108dp"\n'
            '    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
            f'    <group\n        android:pivotX="{FIT_PIVOT[0]}"\n        android:pivotY="{FIT_PIVOT[1]}"\n        android:scaleX="{FIT}"\n        android:scaleY="{FIT}">\n'
            f'    <group\n        android:pivotX="{PIVOT[0]}"\n        android:pivotY="{PIVOT[1]}"\n'
            f'        android:rotation="{TILT}">\n{body}\n    </group>\n{rest}\n    </group>\n</vector>\n')


def background_xml():
    return (HEADER + '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    xmlns:aapt="http://schemas.android.com/aapt"\n'
            '    android:width="108dp"\n    android:height="108dp"\n'
            '    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
            '    <path android:pathData="M0,0h108v108h-108z">\n'
            '        <aapt:attr name="android:fillColor">\n'
            '            <gradient\n                android:type="linear"\n'
            '                android:startX="20" android:startY="0"\n'
            '                android:endX="88" android:endY="108">\n'
            f'                <item android:offset="0.0" android:color="{BG_TOP}" />\n'
            f'                <item android:offset="1.0" android:color="{BG_BOTTOM}" />\n'
            '            </gradient>\n        </aapt:attr>\n    </path>\n'
            '    <!-- Soft desk-lamp glow behind Nooki -->\n'
            '    <path android:pathData="M0,0h108v108h-108z">\n'
            '        <aapt:attr name="android:fillColor">\n'
            '            <gradient\n                android:type="radial"\n'
            '                android:centerX="58" android:centerY="50"\n'
            '                android:gradientRadius="42">\n'
            f'                <item android:offset="0.0" android:color="#AA{GLOW[1:]}" />\n'
            f'                <item android:offset="1.0" android:color="#00{GLOW[1:]}" />\n'
            '            </gradient>\n        </aapt:attr>\n    </path>\n</vector>\n')


def monochrome_xml():
    # Single-colour silhouette for Android 13+ themed icons; features are cut out with evenOdd.
    face = " ".join([HEAD, EYE_L, WINK, NOSE_P])
    ears = " ".join([ear_path(EAR_L), ear_path(mirror(EAR_L))])
    return (HEADER + '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="108dp"\n    android:height="108dp"\n'
            '    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
            f'    <group\n        android:pivotX="{FIT_PIVOT[0]}"\n        android:pivotY="{FIT_PIVOT[1]}"\n        android:scaleX="{FIT}"\n        android:scaleY="{FIT}">\n'
            f'    <group\n        android:pivotX="{PIVOT[0]}"\n        android:pivotY="{PIVOT[1]}"\n'
            f'        android:rotation="{TILT}">\n'
            f'        <path\n            android:fillColor="#FFFFFFFF"\n            android:pathData="{ears}" />\n'
            f'        <path\n            android:fillColor="#FFFFFFFF"\n            android:fillType="evenOdd"\n'
            f'            android:pathData="{face}" />\n    </group>\n'
            f'    <path\n        android:fillColor="#FFFFFFFF"\n        android:pathData="{BELL_P}" />\n'
            f'    <path\n        android:strokeColor="#FFFFFFFF"\n        android:strokeWidth="1.6"\n'
            f'        android:strokeLineCap="round"\n        android:pathData="{RING_1} {RING_2}" />\n'
            '    </group>\n</vector>\n')


def preview_svg(mask="circle"):
    tilted, upright = fg_shapes()
    clip = ('<circle cx="54" cy="54" r="54"/>' if mask == "circle"
            else '<path d="M54,0 C94,0 108,14 108,54 C108,94 94,108 54,108 C14,108 0,94 0,54 C0,14 14,0 54,0 Z"/>')
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108">'
            f'<defs><clipPath id="m">{clip}</clipPath>'
            f'<linearGradient id="bg" x1="20" y1="0" x2="88" y2="108" gradientUnits="userSpaceOnUse">'
            f'<stop offset="0" stop-color="{BG_TOP}"/><stop offset="1" stop-color="{BG_BOTTOM}"/></linearGradient>'
            f'<radialGradient id="glow" cx="58" cy="50" r="42" gradientUnits="userSpaceOnUse">'
            f'<stop offset="0" stop-color="{GLOW}" stop-opacity="0.67"/><stop offset="1" stop-color="{GLOW}" stop-opacity="0"/>'
            f'</radialGradient></defs><g clip-path="url(#m)">'
            f'<rect width="108" height="108" fill="url(#bg)"/><rect width="108" height="108" fill="url(#glow)"/>'
            f'<g transform="translate({FIT_PIVOT[0]} {FIT_PIVOT[1]}) scale({FIT}) translate({-FIT_PIVOT[0]} {-FIT_PIVOT[1]})">'
            f'<g transform="rotate({TILT} {PIVOT[0]} {PIVOT[1]})">' + "".join(svg_path(*s) for s in tilted) + "</g>"
            + "".join(svg_path(*s) for s in upright) + "</g></g></svg>")


def main():
    with open(os.path.join(RES, "drawable", "ic_launcher_foreground.xml"), "w") as f:
        f.write(foreground_xml())
    with open(os.path.join(RES, "drawable", "ic_launcher_background.xml"), "w") as f:
        f.write(background_xml())
    with open(os.path.join(RES, "drawable", "ic_launcher_monochrome.xml"), "w") as f:
        f.write(monochrome_xml())
    if len(sys.argv) > 1:
        os.makedirs(sys.argv[1], exist_ok=True)
        for mask in ("circle", "squircle"):
            with open(os.path.join(sys.argv[1], f"icon_{mask}.svg"), "w") as f:
                f.write(preview_svg(mask))
    print("Icon drawables written to", os.path.abspath(os.path.join(RES, "drawable")))


if __name__ == "__main__":
    main()
